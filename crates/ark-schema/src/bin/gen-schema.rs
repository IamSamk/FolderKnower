//! Writes `schema/architecture.schema.json` and `apps/desktop/src/gen/*.ts`.
//!
//! Run from anywhere: `cargo run -p ark-schema --bin gen-schema`.
//! CI runs it and fails if `git diff` shows the committed files are stale.

use std::{fs, path::Path};

use ark_schema::{SystemArchitectureGraph, json_schema_string};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");

    let schema_dir = root.join("schema");
    fs::create_dir_all(&schema_dir)?;
    fs::write(
        schema_dir.join("architecture.schema.json"),
        json_schema_string(),
    )?;

    let ts_dir = root.join("apps/desktop/src/gen");
    if ts_dir.exists() {
        fs::remove_dir_all(&ts_dir)?;
    }
    fs::create_dir_all(&ts_dir)?;
    SystemArchitectureGraph::export_all(&Config::new().with_out_dir(&ts_dir))?;

    // Barrel file so the app can `import type { ... } from "./gen"`.
    let mut names: Vec<String> = fs::read_dir(&ts_dir)?
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .filter_map(|n| n.strip_suffix(".ts").map(str::to_owned))
        .collect();
    names.sort();
    let mut index =
        String::from("// Generated by `cargo run -p ark-schema --bin gen-schema`. Do not edit.\n");
    for n in &names {
        index.push_str(&format!("export type * from \"./{n}\";\n"));
    }
    fs::write(ts_dir.join("index.ts"), index)?;

    println!("wrote schema/architecture.schema.json and apps/desktop/src/gen/");
    Ok(())
}
